#include <iostream>
using namespace std;
int main()
{
	int mask =0;//{0}
	mask |=(1<<1);//00000|00010=00010{1}
	mask |=(1<<3);//00010|01000=01010{1,3}
	mask |=(1<<4);//10000|01010=11010{1,3,4}
	
	if(mask & (1<<3))cout << "yes";//11010 & 01000=01000
	
	mask &= ~(1<<1);//11010 & 11101=11000{3,4}
	
	
	for(int sub=mask;sub;sub = (sub-1)& mask)//每次
	{
		cout << sub <<" ";
	}
	//11000
	//10111 & 11000=10000
	//01111 & 11000=01000
	//00111 & 11000=00000
	cout << "\n";
	return 0;
}
